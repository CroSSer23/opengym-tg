#!/usr/bin/env node
// Regenerates the per-language exercise instruction packs in frontend/src/instr/.
//
// Two sources, because the upstream dataset does not cover every language openGym's UI does.
//
//   UPSTREAM  es fr it tr ru zh hi pl ko - read straight out of instruction_steps[lang].
//   LOCAL     uk de pt                   - translated in this repo, one JSON map per language
//                                          under scripts/instructions/, keyed by the English
//                                          step. Kept as source rather than only as a built
//                                          pack so the work is reviewable and survives the
//                                          dataset gaining exercises.
//
//   node scripts/build-instructions.mjs [path-to-exercises.json]
//
// Without an argument the dataset is downloaded from the upstream repo.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const UPSTREAM = 'https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/main/data/exercises.json'
const DATASET_LANGS = ['es', 'fr', 'it', 'tr', 'ru', 'zh', 'hi', 'pl', 'ko']
const LOCAL_LANGS = ['uk', 'de', 'pt']

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'frontend', 'src', 'instr')
const mapDir = join(root, 'scripts', 'instructions')

// The locally-translated languages key off the English steps, which already ship in this repo
// inside exercises-data.js. Reading them from there means `--local` needs no network and no
// 17 MB download just to rebuild a pack whose translations live here anyway.
const localOnly = process.argv.includes('--local')

let data = null
if (!localOnly) {
  let raw
  if (process.argv[2] && process.argv[2] !== '--local') {
    raw = readFileSync(process.argv[2], 'utf8')
  } else {
    console.log('Downloading upstream dataset…')
    const res = await fetch(UPSTREAM)
    if (!res.ok) throw new Error('Download failed: HTTP ' + res.status)
    raw = await res.text()
  }
  data = JSON.parse(raw)
}

/** [{ id, en: [steps] }] for the local path, out of the bundled English data. */
async function englishSteps() {
  if (data) return data.map(ex => ({ id: ex.id, en: (ex.instruction_steps && ex.instruction_steps.en) || [] }))
  const { EXDB } = await import(new URL('../frontend/src/lib/exercises-data.js', import.meta.url))
  return EXDB.map(ex => ({ id: ex.id, en: ex.st || [] }))
}

mkdirSync(outDir, { recursive: true })

function write(lang, pack) {
  const file = join(outDir, lang + '.js')
  writeFileSync(file, '// generated by scripts/build-instructions.mjs — do not edit\nexport default ' + JSON.stringify(pack) + '\n')
  return Object.keys(pack).length
}

for (const lang of localOnly ? [] : DATASET_LANGS) {
  const pack = {}
  for (const ex of data) {
    const steps = ex.instruction_steps && ex.instruction_steps[lang]
    if (steps && steps.length) pack[ex.id] = steps
  }
  console.log(`${lang}: ${write(lang, pack)} exercises (upstream)`)
}

const english = await englishSteps()
for (const lang of LOCAL_LANGS) {
  const mapFile = join(mapDir, lang + '.json')
  if (!existsSync(mapFile)) { console.log(`${lang}: no translation map yet, skipped`); continue }
  const map = JSON.parse(readFileSync(mapFile, 'utf8'))
  const pack = {}
  let partial = 0
  for (const ex of english) {
    const steps = ex.en
    if (!steps || !steps.length) continue
    const out = steps.map(s => map[s])
    // All or nothing per exercise. A half-translated list reads as a bug, and falling the
    // whole exercise back to English is both honest and legible.
    if (out.every(Boolean)) pack[ex.id] = out
    else partial++
  }
  console.log(`${lang}: ${write(lang, pack)} exercises (local map)` + (partial ? `, ${partial} still fall back to English` : ''))
}