#!/usr/bin/env node
// Regenerates the per-language exercise name packs in frontend/src/names/.
//
// The upstream dataset names every exercise in English only — it translates the instruction
// steps for nine languages but never the name above them, so "Assisted Standing Triceps
// Extension (With Towel)" sat in the middle of an otherwise Ukrainian screen. The names are
// translated in this repo instead, one JSON map per language under scripts/exercise-names/,
// keyed by the English name so the work survives the dataset gaining exercises.
//
//   node scripts/build-exercise-names.mjs
//
// Names are keyed by name rather than by id because the dataset repeats a handful of them,
// and because a map a human can read is a map a human can review.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const LANGS = ['uk', 'ru']

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'frontend', 'src', 'names')
const mapDir = join(root, 'scripts', 'exercise-names')

const { EXDB } = await import(new URL('../frontend/src/lib/exercises-data.js', import.meta.url))

// The dataset's English names are lowercase and the stylesheet title-cases them; a pack is
// rendered as written, so the first letter is settled here rather than left to whoever wrote
// the map. Names that open with a digit ("3/4 sit-up", "45° side bend") are untouched.
const capitalise = s => s.charAt(0).toUpperCase() + s.slice(1)

mkdirSync(outDir, { recursive: true })

for (const lang of LANGS) {
  const mapFile = join(mapDir, lang + '.json')
  if (!existsSync(mapFile)) { console.log(`${lang}: no translation map yet, skipped`); continue }
  const map = JSON.parse(readFileSync(mapFile, 'utf8'))
  const pack = {}
  let missing = 0
  for (const ex of EXDB) {
    const name = map[ex.n]
    if (name) pack[ex.id] = capitalise(name)
    else missing++
  }
  const file = join(outDir, lang + '.js')
  writeFileSync(file, '// generated by scripts/build-exercise-names.mjs — do not edit\nexport default ' + JSON.stringify(pack) + '\n')
  console.log(`${lang}: ${Object.keys(pack).length} exercises` + (missing ? `, ${missing} still fall back to English` : ''))
}
